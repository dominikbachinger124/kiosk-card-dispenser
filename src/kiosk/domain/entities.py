"""Domain entities: accounts, cards, and sessions.

Entities are immutable. State changes return a new instance that the
repository persists.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from datetime import datetime
from enum import StrEnum

from kiosk.domain.errors import InvalidCardStateError


class CardStatus(StrEnum):
    """Lifecycle state of a card."""

    ACTIVE = "active"
    RECYCLED = "recycled"
    CANCELLED = "cancelled"


RETENTION_YEARS = 1


@dataclass(frozen=True, slots=True)
class Account:
    """One customer account. Identified only by the salted hash of the card UID.

    Attributes:
        id: Primary key.
        id_hash: Salted SHA-256 of the identifying card UID.
        created_at: Creation time, UTC.
        closed_at: Closing time, UTC, or None while open.
    """

    id: int
    id_hash: str
    created_at: datetime
    closed_at: datetime | None = None

    @property
    def is_closed(self) -> bool:
        """True once the account is locked; no further bookings are possible."""
        return self.closed_at is not None

    def retention_until(self) -> datetime | None:
        """Earliest time the closed account may be purged; None while open.

        The retention period is one year after the closing time. Purging is
        a separate, later step and is not part of the booking rules.
        """
        if self.closed_at is None:
            return None
        target_year = self.closed_at.year + RETENTION_YEARS
        try:
            return self.closed_at.replace(year=target_year)
        except ValueError:
            # 29 February has no counterpart in a non-leap year: use 1 March.
            return self.closed_at.replace(year=target_year, day=1, month=3)


@dataclass(frozen=True, slots=True)
class Card:
    """A physical K720 card assigned to one account.

    Attributes:
        id: Primary key.
        uid_hash: Salted SHA-256 of the card UID.
        account_id: Owning account.
        status: Current lifecycle state.
        issued_at: Issue time, UTC.
        recycled_at: Recycling time, UTC, if recycled.
        cancelled_at: Cancellation time, UTC, if cancelled.
    """

    id: int
    uid_hash: str
    account_id: int
    status: CardStatus
    issued_at: datetime
    recycled_at: datetime | None = None
    cancelled_at: datetime | None = None

    def recycle(self, at: datetime) -> Card:
        """Mark an active card as recycled.

        Raises:
            InvalidCardStateError: If the card is not active.
        """
        if self.status is not CardStatus.ACTIVE:
            raise InvalidCardStateError(f"cannot recycle a {self.status} card")
        return replace(self, status=CardStatus.RECYCLED, recycled_at=at)

    def cancel(self, at: datetime) -> Card:
        """Mark an active card as cancelled.

        Raises:
            InvalidCardStateError: If the card is not active.
        """
        if self.status is not CardStatus.ACTIVE:
            raise InvalidCardStateError(f"cannot cancel a {self.status} card")
        return replace(self, status=CardStatus.CANCELLED, cancelled_at=at)


@dataclass(frozen=True, slots=True)
class Session:
    """Technical metadata of one user or admin interaction.

    Attributes:
        id: Session identifier, generated by the caller.
        flow: Flow name, e.g. ``issue`` or ``topup``.
        started_at: Start time, UTC.
        ended_at: End time, UTC, while open None.
        outcome: Result code, set when the session ends.
    """

    id: str
    flow: str
    started_at: datetime
    ended_at: datetime | None = None
    outcome: str | None = None
